# ── 開跑前：anchor 必須逐字出現在原文，否則整批拒跑 ──────────────────
import json
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from contextvars import copy_context

from app.core import db as _db
from app.core import source_mapping as _srcmap
from app.core.db import source_registry as _reg
from app.judge import prejudge as _prejudge

_spec = _reg.spec_for("reviews")
_rows = {str(it.get(_spec.natural_key)): it for it in _db.get_items_by_ids(list(GOLD), "reviews")}
# 校驗基準必須是**判官實際看到的那串文字**，故復用 prejudge._text_of（它在 content 前補「標題：」一行）。
# ⚠️ 只比對 content 會誤殺標題型金標——標題常單獨承載問題點（標題罵、內文只剩情緒或建議），實測 4/200 是這型。
_texts = {r: _prejudge._text_of({**_srcmap.normalize_row("reviews", it), "raw": it}) for r, it in _rows.items()}
_bad = [f"{s}：anchor「{a}」不在原文中" for s, (_c, a, _w) in GOLD.items() if a and a not in _texts.get(s, "")]
if miss := [s for s in GOLD if s not in _texts]:
    _bad.append(f"取不到原文：{miss}")
if _bad:
    raise SystemExit("❌ 金標 anchor 校驗失敗（拒跑，避免朝錯誤標籤優化）：\n  " + "\n  ".join(_bad))
_stars = {r: str(it.get(_spec.score_col) or "") for r, it in _rows.items()}
print(f"✅ anchor 校驗通過：{len(GOLD)} 則金標全部有原文逐字依據")

_OPEN = {s for s, (_c, _a, w) in GOLD.items() if w.startswith("OPEN=")}
_WORKERS = int(__import__("os").environ.get("GOLD_WORKERS", "8"))


def _judge(sid: str) -> tuple[str, str, list[str]]:
    """回 (rec_oid, 主歸因 code 或 '—', 全部歸因字串)。"""
    fs = [f.model_dump() for f in prejudge.to_findings(_build_eval_item("reviews", sid), model="gpt-5.4-mini")]
    attrs = [f for f in fs if f.get("l1_domain_code")]
    prim = next((f for f in attrs if f.get("is_primary")), attrs[0] if attrs else None)
    return sid, (prim["l2_code"] if prim else "—"), [
        f"{f['l2_code']}@{f.get('confidence') or 0:.2f}" for f in attrs
    ]


got: dict[str, tuple[str, list[str]]] = {}
with ThreadPoolExecutor(max_workers=_WORKERS) as ex:
    futs = [ex.submit(copy_context().run, _judge, s) for s in GOLD]
    for i, f in enumerate(as_completed(futs), 1):
        sid, code, alls = f.result()
        got[sid] = (code, alls)
        if i % 40 == 0 or i == len(futs):
            print(f"  進度 {i}/{len(futs)}", flush=True)

hit = miss_ = fp = fn = 0
rows_out = []
for sid, (want, _a, why) in GOLD.items():
    code, alls = got[sid]
    if code == want:
        hit += 1
        m = "✅"
    elif want == "—":
        fp += 1
        m = "❌多報"
    elif code == "—":
        fn += 1
        m = "❌漏判"
    else:
        miss_ += 1
        m = "❌收錯"
    rows_out.append((m, sid, want, code, alls, why))

n = len(GOLD)
print(f"\n  主歸因準確率 {hit}/{n} = {hit / n:.1%}   收錯 {miss_}  多報 {fp}  漏判 {fn}")
c_ok = sum(1 for m, s, *_ in rows_out if m == "✅" and s not in _OPEN)
c_n = n - len(_OPEN)
print(f"  排除 {len(_OPEN)} 則待拍板：{c_ok}/{c_n} = {c_ok / c_n:.1%}")

# 母體加權：分層抽樣的樣本準確率會被低星層放大，加權後才是線上真實表現
num = den = 0.0
for m, sid, *_ in rows_out:
    if sid in _OPEN:
        continue
    w = _STRATUM_WEIGHT.get(_stars.get(sid, ""), 1.0)
    den += w
    num += w * (m == "✅")
print(f"  **母體加權準確率 {num / den:.1%}**（依星等分層權重還原 39,649 則母體）")

by_star = defaultdict(lambda: [0, 0])
for m, sid, *_ in rows_out:
    if sid in _OPEN:
        continue
    b = by_star[_stars.get(sid, "?")]
    b[1] += 1
    b[0] += m == "✅"
print("  各星等：" + "  ".join(f"{k}★ {v[0]}/{v[1]}={v[0] / v[1]:.0%}" for k, v in sorted(by_star.items())))
print(f"  錯誤型態：{dict(Counter(m for m, s, *_ in rows_out if m != '✅' and s not in _OPEN))}")

print("\n  ── 不一致明細（非待拍板）──")
for m, sid, want, code, alls, why in rows_out:
    if m != "✅" and sid not in _OPEN:
        print(f"  {m} {sid} 金標 {want:<6} → 實得 {code:<6} 全部 {alls}  ｜{why[:60]}")
